-- BE-02: pricing and reorder suggestions. pending_key = productId|TRIGGER while PENDING, NULL afterwards.
-- The unique constraint allows many NULLs, so it acts as "at most one PENDING per product + trigger" (BR-4).
create table pricing_suggestions (
  id                bigint generated by default as identity primary key,
  product_id        varchar(32)    not null references products (id),
  current_price     numeric(12, 2) not null,
  recommended_price numeric(12, 2) not null,
  change_pct        numeric(8, 2)  not null,
  direction         varchar(10)    not null,
  confidence        numeric(4, 3)  not null,
  reasoning         varchar(4000)  not null,
  status            varchar(20)    not null,
  trigger_reason    varchar(20)    not null,
  source            varchar(20)    not null,
  strategy_key      varchar(40)    not null,
  fallback_reason   varchar(30),
  pending_key       varchar(80),
  decided_at        timestamp with time zone,
  decision_note     varchar(500),
  version           bigint         not null default 0,
  created_at        timestamp with time zone not null,
  constraint uq_pricing_pending_key unique (pending_key)
);
create index idx_pricing_status_product on pricing_suggestions (status, product_id);

create table reorder_suggestions (
  id                   bigint generated by default as identity primary key,
  product_id           varchar(32)   not null references products (id),
  current_stock        integer       not null,
  recommended_quantity integer       not null,
  lead_time_days       integer       not null,
  confidence           numeric(4, 3) not null,
  reasoning            varchar(4000) not null,
  status               varchar(20)   not null,
  trigger_reason       varchar(20)   not null,
  source               varchar(20)   not null,
  strategy_key         varchar(40)   not null,
  fallback_reason      varchar(30),
  pending_key          varchar(80),
  decided_at           timestamp with time zone,
  decision_note        varchar(500),
  version              bigint        not null default 0,
  created_at           timestamp with time zone not null,
  constraint uq_reorder_pending_key unique (pending_key)
);
create index idx_reorder_status_product on reorder_suggestions (status, product_id);
