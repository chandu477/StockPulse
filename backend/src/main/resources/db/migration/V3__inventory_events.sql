-- BE-02: append-only history of stock changes (ORDER, ADJUST, INBOUND).
create table inventory_events (
  id             bigint generated by default as identity primary key,
  product_id     varchar(32) not null references products (id),
  event_type     varchar(20) not null,
  quantity_delta integer     not null,
  stock_after    integer     not null,
  velocity_after integer     not null,
  created_at     timestamp with time zone not null
);
create index idx_inventory_events_product on inventory_events (product_id, created_at);
